"""Generate the phypara serialization order (69 segments, 5170 halfwords)
from docsClean/appendix-phypara-order.md as a flat C table of PHY indices.

The order is the quickboot ABI: entry k of the serialized stream comes from
PHY CSR index phypara_order[k]. Nothing is sorted, merged or deduplicated.
"""
import re
import sys

ROW = re.compile(r"^\|\s*(\d+)\s*\|\s*`0x([0-9a-fA-F]+)`\s*\|\s*(\d+)\s*\|\s*(sparse|sequential)\s*\|\s*(.*?)\s*\|\s*$")
SEQ = re.compile(r"^(\d+)\.\.(\d+)")


def parse(path):
    segs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = ROW.match(line)
            if not m:
                continue
            idx, base, count, kind, rest = m.groups()
            base, count = int(base, 16), int(count)
            if kind == "sparse":
                offs = [int(x) for x in rest.split(",")]
            else:
                s = SEQ.match(rest)
                lo, hi = int(s.group(1)), int(s.group(2))
                offs = list(range(lo, hi + 1))
            if len(offs) != count or int(idx) != len(segs):
                sys.exit(f"segment {idx}: inconsistent row")
            segs.append((base, kind, offs))
    return segs


def emit_fw(segs, dst):
    """Compact table for the PMU firmware: 69 segment descriptors plus the
    offsets of the sparse segments (sequential ones store their start)."""
    out = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/gen_phypara.py --fw from",
        " * docsClean/appendix-phypara-order.md -- do not edit. */",
        "#include \"common/phypara.h\"",
        "",
        "const struct phypara_seg phypara_segs[PHYPARA_NSEG] = {",
    ]
    offs_all = []
    for base, kind, offs in segs:
        if kind == "sequential":
            out.append(f"\t{{ 0x{base:06x}, {len(offs)}, {offs[0]}, 1 }},")
        else:
            out.append(f"\t{{ 0x{base:06x}, {len(offs)}, {len(offs_all)}, 0 }},")
            offs_all += offs
    out += ["};", "", f"const uint16_t phypara_offsets[{len(offs_all)}] = {{"]
    for i in range(0, len(offs_all), 12):
        out.append("\t" + " ".join(f"{v}," for v in offs_all[i:i + 12]))
    out += ["};", ""]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


def main(src, dst, fw=False):
    segs = parse(src)
    flat = [b + o for b, _, offs in segs for o in offs]
    if len(segs) != 69 or len(flat) != 5170:
        sys.exit(f"parsed {len(segs)} segments / {len(flat)} halfwords")
    if fw:
        emit_fw(segs, dst)
        return
    out = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/gen_phypara.py from",
        " * docsClean/appendix-phypara-order.md -- do not edit. */",
        "#include <stdint.h>",
        "",
        "#define PHYPARA_NSEG 69",
        "#define PHYPARA_COUNT 5170",
        "",
        "/* first serialized position of each segment */",
        "const uint16_t phypara_seg_start[PHYPARA_NSEG + 1] = {",
    ]
    pos, starts = 0, []
    for _, _, offs in segs:
        starts.append(pos)
        pos += len(offs)
    starts.append(pos)
    for i in range(0, len(starts), 10):
        out.append("\t" + " ".join(f"{s}," for s in starts[i:i + 10]))
    out += ["};", "", "/* PHY CSR index of every serialized halfword */",
            "const uint32_t phypara_order[PHYPARA_COUNT] = {"]
    for i in range(0, len(flat), 8):
        out.append("\t" + " ".join(f"0x{v:06x}," for v in flat[i:i + 8]))
    out += ["};", ""]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--fw"]
    if len(args) != 2:
        sys.exit("usage: gen_phypara.py [--fw] <appendix.md> <out.c>")
    main(args[0], args[1], fw="--fw" in sys.argv)
