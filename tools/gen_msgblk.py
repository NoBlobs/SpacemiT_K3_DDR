"""Generate src/common/msgblk_fields.h from the docsClean message block appendix.

Only interface facts are emitted: byte offset, size, direction and C type of
every field of the 320-byte LPDDR5 1D message block.
"""
import re
import sys

ROW = re.compile(
    r"^\|\s*(\d+)\s*\|\s*`0x([0-9a-fA-F]+)`\s*\|\s*`0x([0-9a-fA-F]+)`\s*\|"
    r"\s*([A-Za-z/]+)\s*\|\s*`([a-z0-9_]+)`\s*\|\s*`([A-Za-z0-9_]+)`\s*\|")

SIZES = {"uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2}
DIRS = {"in": "MB_IN", "out": "MB_OUT", "n/a": "MB_NA"}


def main(src, dst):
    fields = []
    with open(src, encoding="utf-8") as f:
        for line in f:
            m = ROW.match(line)
            if m:
                idx, off, csr, d, ctype, name = m.groups()
                fields.append((int(idx), int(off, 16), int(csr, 16),
                               d.lower(), ctype, name))
    if len(fields) != 293:
        sys.exit(f"expected 293 fields, parsed {len(fields)}")
    end = 0
    for i, (idx, off, csr, d, ctype, name) in enumerate(fields):
        if idx != i or off != end or csr != 0x58000 + off // 2:
            sys.exit(f"layout mismatch at field {idx} {name}")
        end = off + SIZES[ctype]
    if end != 0x140:
        sys.exit(f"block size {end:#x} != 0x140")

    out = [
        "/* SPDX-License-Identifier: GPL-2.0-or-later */",
        "/* Generated by tools/gen_msgblk.py from",
        " * docsClean/appendix-message-block-fields.md -- do not edit. */",
        "#ifndef MSGBLK_FIELDS_H",
        "#define MSGBLK_FIELDS_H",
        "",
        "#define MB_SIZE 0x140",
        "#define MB_NFIELDS %d" % len(fields),
        "#define MB_IN  0",
        "#define MB_OUT 1",
        "#define MB_NA  2",
        "",
        "/* MB_<name>: byte offset; MB_<name>_SZ: size; MB_<name>_DIR: direction */",
    ]
    for idx, off, csr, d, ctype, name in fields:
        out.append("#define MB_%-28s 0x%03x" % (name, off))
        out.append("#define MB_%-28s %d" % (name + "_SZ", SIZES[ctype]))
        out.append("#define MB_%-28s %s" % (name + "_DIR", DIRS[d]))
    out += [
        "",
        "/* X-macro list: X(name, offset, size, dir, signed) */",
        "#define MB_FIELD_LIST(X) \\",
    ]
    for idx, off, csr, d, ctype, name in fields:
        out.append("\tX(%s, 0x%03x, %d, %s, %d) \\" % (
            name, off, SIZES[ctype], DIRS[d], 1 if ctype.startswith("int") else 0))
    out += ["", "#endif", ""]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_msgblk.py <appendix.md> <out.h>")
    main(sys.argv[1], sys.argv[2])
